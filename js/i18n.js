function initLanguageToggle() {
  const langToggleBtn = document.getElementById('lang-toggle-btn');
  const langIndicator = document.getElementById('lang-indicator');

  const savedLang = localStorage.getItem('faril_lang') || 'en';

  function applyLanguage(lang) {
    document.documentElement.setAttribute('lang', lang);
    if (langIndicator) {
      langIndicator.textContent = lang.toUpperCase();
    }

    const data = I18N_DATA[lang] || I18N_DATA.en;

    // Standard text nodes
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (data[key] !== undefined) {
        el.textContent = data[key];
      }
    });

    // HTML nodes (containing spans, strong, br, etc.)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (data[key] !== undefined) {
        el.innerHTML = data[key];
      }
    });

    // Input placeholder attributes
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (data[key] !== undefined) {
        el.setAttribute('placeholder', data[key]);
      }
    });

    localStorage.setItem('faril_lang', lang);

    if (window.lucide && typeof window.lucide.createIcons === 'function') {
      window.lucide.createIcons();
    }
  }

  applyLanguage(savedLang);

  if (langToggleBtn) {
    langToggleBtn.addEventListener('click', () => {
      const current = localStorage.getItem('faril_lang') || 'en';
      const next = current === 'en' ? 'id' : 'en';
      applyLanguage(next);
    });
  }
}
